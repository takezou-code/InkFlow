package com.vic.inkflow.ui.theme

import androidx.compose.ui.unit.dp

/**
 * 觸控目標與手勢把手尺寸。
 *
 * 為什麼是 dp 而不是 px：把手常數若寫死物理 px，在高密度螢幕（density 2.75 的平板）
 * 換算回 dp 會大幅缩水——48px 命中框只剩 17.5dp，遠低於 Material 的 48dp 最低標準，
 * 使用者必須瞄準才能抓到。dp 保證「不管什麼螢幕都是同樣的手指體驗」。
 *
 * 分成兩層（Material 3 明確區分）：
 * - **觸控目標（hit）**：畫面上看不到，但在視覺之外。使用者只靠它抓，決定好不好用。
 * - **視覺（visual）**：真的畫出來的那顆。決定好不好看，小一點反而精緻。
 *
 * 引用：`InkCanvasGeometry.kt`（圖/字/套索/筆跡四種選取框共用）。
 */
object Handles {
    /** 命中半徑。24dp → 螢幕上 48×48dp 觸控框，Material 3 最低標準（≈9mm 實體）。 */
    val TouchRadius = 24.dp

    /**
     * 視覺半徑。4dp → 8dp 實心點。
     * 刻意比觸控目標小很多：視覺只負責「告訴你這裡能抓」，抓不抓得到靠 TouchRadius。
     * 視覺畫太大反而會蓋住內容、讓選取框看起來笨重。
     */
    val VisualRadius = 4.dp

    /** 光暈半徑（halo），比視覺大一圈做玻璃感。 */
    val HaloRadius = 6.dp

    /**
     * 旋轉把手懸在選取框上方多遠。28dp ≈ 旋轉把手直徑的 3.5 倍，
     * 留足空間讓「連桿線」看清楚它是獨立功能、不是某個角。
     */
    val RotGap = 28.dp

    /**
     * 抓住把手時的放大倍率。1.0 → 1.35。
     *
     * 注意這跟「按鈕按壓要縮小 0.94」是相反的，因為語意不同：
     * 按鈕是「壓下去執行」，把手是「抓住了開始拖」——放大是**確認抓到了**的正向回饋。
     * 1.35 是有感但不至於大到遮住正在被縮放的內容。
     */
    const val PressedScale = 1.35f

    /**
     * 抓住把手時選取框邊線加粗倍率（1f = 不變）。
     * 用線寬變化而非整框縮放——線加粗不影響內部內容的可視面積。
     */
    const val PressedStrokeScale = 1.4f
}